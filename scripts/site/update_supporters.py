#!/usr/bin/env python3
"""Writes the Supporters wall of site/about.html from resources/supporters.txt (COM-8), the same file Sonora's About
window reads. Run after editing that file, then publish the site.

Usage: python3 scripts/site/update_supporters.py [--check]   (--check: exit 1 when the page is out of date)
"""
import html
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TIERS = [("studio", "Studio"), ("producer", "Producers"), ("supporter", "Supporters"), ("coffee", "Coffees")]
START, END = "<!-- supporters:start", "<!-- supporters:end -->"
KOFI = "https://ko-fi.com/lordillusions"


def groups():
    names = {key: [] for key, _ in TIERS}
    for raw in (ROOT / "resources/supporters.txt").read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "|" not in line:
            continue
        tier, name = (part.strip() for part in line.split("|", 1))
        if tier.lower() in names and name:
            names[tier.lower()].append(name[:60])
    return [(title, names[key]) for key, title in TIERS if names[key]]


def block():
    found = groups()
    lead = f'{START} (generated by scripts/site/update_supporters.py from resources/supporters.txt) -->\n'
    if not found:
        return (lead + f'      <p class="muted">No supporters listed yet. <a href="{KOFI}" target="_blank" rel="noopener">Become the first</a>, '
                "and your name shows here and in Sonora's About window.</p>\n      " + END)
    parts = [lead]
    for title, names in found:
        spans = "".join(f"<span>{html.escape(n)}</span>" for n in names)
        parts.append(f'      <div class="supporter-tier"><h3>{title}</h3><p class="supporter-names">{spans}</p></div>\n')
    parts.append(f'      <p class="muted" style="margin-top:18px"><a href="{KOFI}" target="_blank" rel="noopener">Join them on Ko-fi</a>.</p>\n      {END}')
    return "".join(parts)


def main():
    page = ROOT / "site/about.html"
    text = page.read_text(encoding="utf-8")
    a, b = text.index(START), text.index(END) + len(END)
    updated = text[:a] + block() + text[b:]
    if "--check" in sys.argv:
        sys.exit(0 if updated == text else 1)
    page.write_text(updated, encoding="utf-8")
    print(f"{page}: {sum(len(n) for _, n in groups())} supporters")


if __name__ == "__main__":
    main()
