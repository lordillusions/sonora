#!/usr/bin/env python3
"""Generate our optional minimax sample prototype (DEV-18d).

Requires NumPy and SciPy1.13.1; reads no plugin, vendor coefficient or asset input.
The mathematical specification is an inferred response fit, not proof of a
proprietary generator. The generated design retains measurable interpolation
and stopband differences. Runtime support endpoints are zeroed for continuity.

    python scripts/generate_sample_kernel.py
    python scripts/generate_sample_kernel.py --check

Ordinary minimax FIR design documentation:
https://docs.scipy.org/doc/scipy/reference/generated/scipy.signal.remez.html
"""

import argparse
import hashlib
from pathlib import Path

import numpy as np
import scipy
from scipy import signal

NUMTAPS = 1025
TIME_GRID_RATE = 64.0
PASS_EDGE = 0.45002788566353535
STOP_EDGE = 0.776705943255579
STOP_TO_PASS_WEIGHT = 6683.773348197528


def generate_text():
    if scipy.__version__ != "1.13.1":
        raise RuntimeError("Reproducible generation requires SciPy1.13.1")
    prototype = signal.remez(
        NUMTAPS,
        [0, PASS_EDGE, STOP_EDGE, TIME_GRID_RATE / 2],
        [1, 0],
        weight=[1, STOP_TO_PASS_WEIGHT],
        fs=TIME_GRID_RATE,
        maxiter=60,
        grid_density=32,
    ) * TIME_GRID_RATE
    if not np.isfinite(prototype).all():
        raise RuntimeError("Minimax design returned a nonfinite prototype")
    digest = hashlib.sha256(prototype.astype("<f8").tobytes()).hexdigest()
    lines = [
        "// Generated by scripts/generate_sample_kernel.py (DEV-18d). Do not edit.",
        "// Independent standard Remez FIR math; no vendor data is read or embedded.",
        "// SciPy1.13.1, numtaps1025, fs64, maxiter60/grid_density32; impulse scaled by64.",
        f"// Pass edge{PASS_EDGE:.17g}, stop edge{STOP_EDGE:.17g}, stop/pass weight{STOP_TO_PASS_WEIGHT:.17g}.",
        f"// Generated f64LE SHA256: {digest}",
        "// Fitted specification only: generation equivalence is unproven. Approximate",
        "// coefficient max error3.79e-5 and all-phase response max error1.54e-4 remain.",
        "#pragma once",
        "#include <array>",
        "namespace sonora::dsp::detail",
        "{",
        "inline constexpr std::array<double, 1025> sampleKernelMinimax1025{",
    ]
    for start in range(0, NUMTAPS, 4):
        lines.append("    " + ", ".join(format(value, ".17g") for value in prototype[start:start + 4]) + ",")
    lines.extend(["};", "} // namespace sonora::dsp::detail", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated output without editing it")
    arguments = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "src/dsp/generated/SampleKernelMinimax1025.inc"
    generated = generate_text()
    if arguments.check:
        if not destination.exists() or destination.read_text() != generated:
            raise SystemExit("Generated sample prototype differs; regenerate with pinned SciPy1.13.1")
        print("Generated sample prototype matches")
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(generated)
    print(destination)


if __name__ == "__main__":
    main()
